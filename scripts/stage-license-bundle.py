#!/usr/bin/env python3
"""Stage the third-party license bundle for the seekdb Python wheel.

The bundle combines the components bundled by this repository (``licenses/``)
with the engine bundle generated from the seekdb source tree, and renders the
inventory, redistribution requirements and a checksum manifest.
"""

import argparse
import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LICENSES = ROOT / "licenses"
PROJECT = {
    "name": "seekdb",
    "source": "https://github.com/oceanbase/seekdb-bindings",
    "license": "Apache-2.0",
    "license_files": ["LICENSE"],
    "notice_files": ["NOTICE"],
}
REQUIRED_FIELDS = (
    "name",
    "version",
    "source",
    "packaged_as",
    "license",
    "modified",
    "license_files",
    "redistribution",
)


def load_components():
    components = []
    for directory in sorted(LICENSES.iterdir()):
        if not directory.is_dir():
            continue
        metadata = directory / "METADATA.json"
        if not metadata.is_file():
            raise ValueError("component directory %s is missing METADATA.json" % directory)
        component = json.loads(metadata.read_text(encoding="utf-8"))
        for field in REQUIRED_FIELDS:
            if field not in component:
                raise ValueError("component %r is missing %s" % (component.get("name"), field))
        if not component["license_files"]:
            raise ValueError("component %s has no license files" % component["name"])
        for relative in component["license_files"]:
            if not (directory / relative).is_file():
                raise ValueError("component %s references missing license file %s" % (
                    component["name"], relative))
        component["directory"] = directory.name
        components.append(component)
    if not components:
        raise ValueError("no component directories found under %s" % LICENSES)
    return components


def load_engine(engine):
    """Read the engine bundle's inventory and mark its components."""
    if engine is None:
        return [], None
    engine = Path(engine)
    inventory = engine / "THIRD_PARTY_COMPONENTS.json"
    if not inventory.is_file():
        raise ValueError("engine bundle is missing THIRD_PARTY_COMPONENTS.json: %s" % inventory)
    data = json.loads(inventory.read_text(encoding="utf-8"))
    components = []
    for component in data.get("components", []):
        component = dict(component)
        component["shipped_in"] = ["seekdb engine"]
        component["directory"] = "seekdb/" + component.get("directory", "").split("/")[-1]
        components.append(component)
    return components, data.get("artifact", {})


def markdown(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def license_cell(component):
    values = []
    for relative in component["license_files"]:
        path = "%s/%s" % (component["directory"], relative)
        values.append("`%s`" % path)
    return "<br>".join(values)


def render_inventory(components, version, source_commit, engine_artifact):
    lines = [
        "# Third-party components",
        "",
        "This inventory is generated by `scripts/stage-license-bundle.py`.",
        "",
        "- Project: `%s`" % PROJECT["name"],
        "- Version: `%s`" % version,
        "- Source commit: `%s`" % (source_commit or "not recorded"),
    ]
    if engine_artifact:
        lines.append("- Engine bundle: `%s %s` (source commit `%s`)" % (
            engine_artifact.get("name", "seekdb"),
            engine_artifact.get("version", "unspecified"),
            engine_artifact.get("source_commit") or "not recorded"))
    lines.extend([
        "",
        "| Component | Version | Upstream source | Packaged as | License | Modified | License text | Redistribution |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ])
    for component in sorted(components, key=lambda item: item["name"].lower()):
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s |" % (
            markdown(component["name"]),
            markdown(component["version"]),
            markdown(component["source"]),
            markdown(component["packaged_as"]),
            markdown(component["license"]),
            markdown(component["modified"]),
            license_cell(component),
            markdown(component["redistribution"]),
        ))
    lines.extend([
        "",
        "The original license and notice texts are under `licenses/<component>/` in",
        "the installed wheel. `REDISTRIBUTION.md` describes the per-component",
        "retention and source/relink requirements.",
        "",
    ])
    return "\n".join(lines)


def render_redistribution(components, engine_artifact):
    lines = [
        "# Redistribution requirements",
        "",
        "This file is generated by `scripts/stage-license-bundle.py`. Preserve the",
        "complete `licenses/` directory when redistributing the seekdb wheel. The",
        "upstream license and notice texts must remain verbatim.",
        "",
        "| Component | Files to retain | Redistribution requirement | Source |",
        "| --- | --- | --- | --- |",
    ]
    for component in sorted(components, key=lambda item: item["name"].lower()):
        requirement = component["redistribution"]
        if component.get("source_offer"):
            requirement += " See `SOURCE-OFFER.txt`."
        lines.append("| %s | %s | %s | %s |" % (
            markdown(component["name"]),
            license_cell(component),
            markdown(requirement),
            markdown(component["source"]),
        ))
    lines.extend([
        "",
        "## General rules",
        "",
        "- Keep `LICENSE`, `NOTICE`, this file, `THIRD_PARTY_COMPONENTS.md` and the",
        "  complete `licenses/` directory together with the wheel.",
        "- Do not rewrite upstream license or notice text. If a component is",
        "  modified, retain its notice and record the modification in the source",
        "  repository.",
        "- If a component is covered by a copyleft license and is bundled, follow",
        "  its source and relink/replacement requirements.",
        "- Separately installed dependencies are not bundled by this wheel. A",
        "  downstream application that redistributes them must preserve the license",
        "  materials from the exact resolved versions.",
        "",
    ])
    if engine_artifact:
        lines.extend([
            "## Engine bundle",
            "",
            "The engine's own inventory and redistribution requirements are in",
            "`licenses/seekdb/THIRD_PARTY_COMPONENTS.md` and",
            "`licenses/seekdb/REDISTRIBUTION.md`.",
            "",
        ])
    return "\n".join(lines)


def copy_file(source, destination):
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)
    destination.chmod(0o644)


def write_manifest(target):
    lines = []
    for path in sorted(target.rglob("*")):
        if path.is_file() and path.name != "MANIFEST.sha256":
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            lines.append("%s  %s" % (digest, path.relative_to(target).as_posix()))
    (target / "MANIFEST.sha256").write_text("\n".join(lines) + "\n", encoding="utf-8")


def stage(output, engine=None, version=None, source_commit=None):
    components = load_components()
    engine_components, engine_artifact = load_engine(engine)
    output = Path(output)
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)

    for name in PROJECT["license_files"] + PROJECT["notice_files"]:
        copy_file(ROOT / name, output / name)
    for component in components:
        directory = output / component["directory"]
        directory.mkdir(parents=True, exist_ok=True)
        for relative in component["license_files"]:
            copy_file(LICENSES / component["directory"] / relative, directory / relative)

    if engine is not None:
        shutil.copytree(engine, output / "seekdb")
    else:
        (output / "SEEKDB_LICENSES.txt").write_text(
            "The seekdb engine license bundle was not available when this wheel was built.\n"
            "Build with scripts/build-seekdb-wheel.sh --seekdb-licenses <dir> to include the\n"
            "engine's THIRD_PARTY_COMPONENTS, license texts and NOTICE.\n",
            encoding="utf-8")

    inventory = {
        "schema_version": 1,
        "artifact": {
            "name": PROJECT["name"],
            "version": version,
            "source_commit": source_commit,
            "license": PROJECT["license"],
        },
        "components": components + engine_components,
    }
    (output / "THIRD_PARTY_COMPONENTS.json").write_text(
        json.dumps(inventory, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (output / "THIRD_PARTY_COMPONENTS.md").write_text(
        render_inventory(components + engine_components, version, source_commit, engine_artifact),
        encoding="utf-8")
    (output / "REDISTRIBUTION.md").write_text(
        render_redistribution(components + engine_components, engine_artifact),
        encoding="utf-8")
    write_manifest(output)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--engine", type=Path, default=None,
                        help="engine license bundle (e.g. a staged seekdb bundle)")
    parser.add_argument("--version", default=None)
    parser.add_argument("--source-commit", default=None)
    arguments = parser.parse_args()
    stage(arguments.output, arguments.engine, arguments.version, arguments.source_commit)
    print("staged license bundle in %s" % arguments.output)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        raise SystemExit(str(error))
